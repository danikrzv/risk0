import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";


const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemasDirectory = path.join(packageRoot, "schemas");

const readSchema = async (name) =>
  JSON.parse(await readFile(path.join(schemasDirectory, name), "utf8"));

const [catalogSchema, requestSchema, responseSchema, radarSchema, bookSchema] = await Promise.all([
  readSchema("catalog.schema.json"),
  readSchema("analysis-request.schema.json"),
  readSchema("analysis-response.schema.json"),
  readSchema("radar.schema.json"),
  readSchema("book.schema.json"),
]);

const values = (schema, definition, property) => {
  const enumValues = schema.$defs?.[definition]?.properties?.[property]?.enum;
  if (!Array.isArray(enumValues) || enumValues.length === 0) {
    throw new Error(`Missing enum ${definition}.${property}`);
  }
  return enumValues;
};

const literalUnion = (enumValues) => enumValues.map(JSON.stringify).join(" | ");
const constArray = (name, enumValues) =>
  `export const ${name} = ${JSON.stringify(enumValues)} as const;`;
const definitionValues = (schema, definition) => {
  const enumValues = schema.$defs?.[definition]?.enum;
  if (!Array.isArray(enumValues) || enumValues.length === 0) {
    throw new Error(`Missing enum ${definition}`);
  }
  return enumValues;
};

const catalogEntityTypes = values(catalogSchema, "CatalogEntry", "entity_type");
