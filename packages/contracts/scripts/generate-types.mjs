import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";


const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemasDirectory = path.join(packageRoot, "schemas");

const readSchema = async (name) =>
  JSON.parse(await readFile(path.join(schemasDirectory, name), "utf8"));

const [catalogSchema, requestSchema, responseSchema] = await Promise.all([
  readSchema("catalog.schema.json"),
  readSchema("analysis-request.schema.json"),
  readSchema("analysis-response.schema.json"),
]);

const values = (schema, definition, property) => {
  const enumValues = schema.$defs?.[definition]?.properties?.[property]?.enum;
  if (!Array.isArray(enumValues) || enumValues.length === 0) {
    throw new Error(`Missing enum ${definition}.${property}`);
  }
  return enumValues;
};

const literalUnion = (enumValues) => enumValues.map(JSON.stringify).join(" | ");
const constArray = (name, enumValues) =>
  `export const ${name} = ${JSON.stringify(enumValues)} as const;`;

const catalogEntityTypes = values(catalogSchema, "CatalogEntry", "entity_type");
const catalogProvenance = values(catalogSchema, "CatalogEntry", "provenance");
const positionModes = values(requestSchema, "PositionInput", "mode");
const scenarioIds = values(requestSchema, "ScenarioSelection", "scenario_id");
const riskNodeTypes = values(responseSchema, "RiskNode", "node_type");
const freshnessStatuses = values(responseSchema, "RiskNode", "freshness");
const riskEdgeTypes = values(responseSchema, "RiskEdge", "relationship");
const probabilityMethods = values(responseSchema, "ProbabilityEstimate", "method");
const confidenceLevels = values(responseSchema, "ProbabilityEstimate", "confidence");
const recommendationDecisions = values(responseSchema, "Recommendation", "decision");

const generated = `// Generated by scripts/generate-types.mjs. Do not edit directly.

${constArray("CATALOG_ENTITY_TYPES", catalogEntityTypes)}
${constArray("CATALOG_PROVENANCE", catalogProvenance)}
${constArray("POSITION_MODES", positionModes)}
${constArray("SCENARIO_IDS", scenarioIds)}
${constArray("RISK_NODE_TYPES", riskNodeTypes)}
${constArray("FRESHNESS_STATUSES", freshnessStatuses)}
${constArray("RISK_EDGE_TYPES", riskEdgeTypes)}
${constArray("PROBABILITY_METHODS", probabilityMethods)}
${constArray("CONFIDENCE_LEVELS", confidenceLevels)}
${constArray("RECOMMENDATION_DECISIONS", recommendationDecisions)}

export type CatalogEntityType = ${literalUnion(catalogEntityTypes)};
export type CatalogProvenance = ${literalUnion(catalogProvenance)};
export type PositionMode = ${literalUnion(positionModes)};
export type ScenarioId = ${literalUnion(scenarioIds)};
export type RiskNodeType = ${literalUnion(riskNodeTypes)};
export type FreshnessStatus = ${literalUnion(freshnessStatuses)};
export type RiskEdgeType = ${literalUnion(riskEdgeTypes)};
export type ProbabilityMethod = ${literalUnion(probabilityMethods)};
export type ConfidenceLevel = ${literalUnion(confidenceLevels)};
export type RecommendationDecision = ${literalUnion(recommendationDecisions)};
export type DecimalString = string;
export type MetricValue = string | boolean | null;

export interface CatalogEntry {
  entity_id: string;
  chain_id: 1;
  entity_type: CatalogEntityType;
  address_or_market_id: string;
  name: string;
  description: string;
  provenance: CatalogProvenance;
  provenance_label: string;
  supported: boolean;
  supported_modes: PositionMode[];
  lltv: DecimalString | null;
}

export interface CatalogResponse {
  entries: CatalogEntry[];
}

interface PositionInputBase {
  entity_id: string;
  amount: DecimalString;
  numeraire: string;
}

export interface LenderPositionInput extends PositionInputBase {
  mode: "lender";
  collateral_amount?: never;
  debt_amount?: never;
  ltv?: never;
}

export interface BorrowerPositionInput extends PositionInputBase {
  mode: "borrower";
  collateral_amount: DecimalString;
  debt_amount: DecimalString;
  ltv: DecimalString;
}

export type PositionInput = LenderPositionInput | BorrowerPositionInput;

export interface ScenarioSelection {
  scenario_id: ScenarioId;
  severity: DecimalString;
}

export interface RiskNode {
  node_id: string;
  node_type: RiskNodeType;
  label: string;
  metrics: Record<string, MetricValue>;
  provenance: string;
  freshness: FreshnessStatus;
  observed_at: string;
}

export interface RiskEdge {
  source: string;
  target: string;
  relationship: RiskEdgeType;
  exposure_weight: DecimalString | null;
}

export interface RiskGraph {
  nodes: RiskNode[];
  edges: RiskEdge[];
  generated_at: string;
  completeness_warnings: string[];
}

export interface ProbabilityEstimate {
  method: ProbabilityMethod;
  low: DecimalString | null;
  central: DecimalString | null;
  high: DecimalString | null;
  confidence: ConfidenceLevel;
  horizon_days: 30;
  source: string;
  retrieved_at: string;
  freshness: FreshnessStatus;
  explanation: string;
}

export interface ScenarioResult {
  scenario_id: string;
  affected_path: string[];
  stressed_values: Record<string, MetricValue>;
  hard_triggers: string[];
  impact: DecimalString;
  impact_components: Record<string, DecimalString>;
  probability: ProbabilityEstimate;
  confidence: ConfidenceLevel;
  explanation: string;
}

export interface ExitEstimate {
  withdrawable: boolean;
  route: string[];
  slippage: DecimalString;
  fees: DecimalString;
  gas: DecimalString;
  price_impact: DecimalString;
  total_cost: DecimalString;
  quote_age_seconds: number;
  quote_block?: number | null;
  quoted_at: string;
  source: string;
  retrieved_at: string;
  freshness: FreshnessStatus;
  warnings: string[];
}

export interface Recommendation {
  decision: RecommendationDecision;
  expected_loss: DecimalString;
  expected_loss_low?: DecimalString | null;
  expected_loss_high?: DecimalString | null;
  exit_cost: DecimalString;
  triggers: string[];
  dominant_dependency: string | null;
  confidence: ConfidenceLevel;
  explanation: string;
}

export interface AnalysisRequest {
  position: PositionInput;
  scenarios: [ScenarioSelection, ...ScenarioSelection[]];
}

export interface AnalysisResponse {
  graph: RiskGraph;
  scenario_results: ScenarioResult[];
  exit_estimate: ExitEstimate;
  recommendation: Recommendation;
  analyzed_at: string;
}
`;

const outputPath = path.join(packageRoot, "src", "generated.ts");

if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8");

  if (existing !== generated) {
    console.error(
      "Generated contracts are stale. Run `pnpm --filter @risk0/contracts generate`.",
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated);
}
